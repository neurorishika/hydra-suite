@pytest.mark.parametrize("ref,frac,expected", CASES)
def test_resolve_tile_px_frozen_behaviour(ref, frac, expected):
    """Pin the pre-refactor output for every swept input."""
    if isinstance(expected, str):
        with pytest.raises(Exception) as exc:
            resolve_tile_px(ref, frac)
        assert type(exc.value).__name__ == expected
        return
    assert resolve_tile_px(ref, frac) == expected


@pytest.mark.parametrize("ref,frac,expected", CASES)
def test_resolve_tile_px_matches_shared_helper(ref, frac, expected):
    """Direct equivalence with the shared helper wherever it is applicable.

    The shared helper has no ``None``/no-tiling concept, so the cases where
    ``resolve_tile_px`` legitimately returns ``None`` (unknown scale, explicit
    no-tiling) are out of its scope and are covered by the frozen-value test
    above. NaN is likewise excluded: ``tile_size_for_mode``'s
    ``reference_body_px > 0`` gate is False for NaN and falls through to the
    ``auto_model`` branch, whereas ``resolve_tile_px`` raises -- ``tiling.py``
    keeps that guard locally.
    """
    if not isinstance(expected, int):
        return
    if ref != ref or frac is None:  # NaN ref / no-tiling: see docstring
        return
    w, h = tile_size_for_mode(
        geometry_mode="auto_object",
        imgsz=1024,
        reference_body_px=float(ref),
        object_tile_fraction=float(frac),
        slice_width=0,
        slice_height=0,
    )
    assert w == h == expected
